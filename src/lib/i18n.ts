const DICT: Record<Lang, Record<Key, string>> = { en, pl };

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let text = DICT[lang][key];
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  }
  return text;
}

export function detectLang(): Lang {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('pl') ? 'pl' : 'en';
}
